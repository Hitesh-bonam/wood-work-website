/** Words the page script (app.js) needs, sent along with each Telugu page. */
export const SCRIPT_WORDS = ['Photo viewer', 'Close', 'Previous photo', 'Next photo', 'Photo', 'See the full project', 'Project story', 'Play', 'Pause', 'Close story', 'Get a quote on WhatsApp', 'Call us', 'See the price', 'Next: {x}', 'project', 'Like this project?', 'Watch again', 'How many {unit}?', 'Enter a size to see an estimate', 'Enter a number above 0.'];

/** t('Call {phone}', { phone }) in the page's language; unknown words stay English. */
export function translator(lang) {
  const table = lang === 'te' ? TE : {};
  return (text, vars = {}) => String(table[text] ?? text).replace(/\{(\w+)\}/g, (all, key) => (key in vars ? vars[key] : all));
}

export function scriptDictionary(lang) {
  if (lang !== 'te') return null;
  return Object.fromEntries(SCRIPT_WORDS.map((w) => [w, TE[w] ?? w]));
}
